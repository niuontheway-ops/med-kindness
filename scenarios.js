const inferEmotion = (quality, reply) => {
  if (/去世|死了|不想等|嫌他|一个人倒|见他|握他的手|对不起|不甘心|难过|缓一缓|哭|失去|痛苦|不公平/.test(reply)) return "sad";
  if (/害怕|最怕|怕|担心|会死|怎么办|是不是|不敢|喘/.test(reply)) return "afraid";
  if (quality === "excellent") return "relieved";
  return quality === "risky" ? "angry" : "sad";
};

